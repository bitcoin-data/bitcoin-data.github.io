#!/usr/bin/env python3
"""Render a Markdown preview of the dataset entries a branch changes.

Used by CI to show reviewers how an entry will read before it is merged.
Imports the site generator so the preview always reflects what the build would
actually produce. Links are listed, never fetched.

    python3 ci/preview.py --base origin/main --out preview.md
    python3 ci/preview.py --slugs stale-blocks,invalid-blocks --out preview.md
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import build  # noqa: E402  (needs ROOT on the path first)

MARKER = "<!-- dataset-preview -->"

# A pull request comment is capped at 65536 characters; leave room for the
# truncation notice rather than letting the API reject the whole body.
COMMENT_LIMIT = 60000


def changed_slugs(base):
    """Slugs of dataset entries added or modified relative to base."""
    try:
        out = subprocess.run(
            ["git", "diff", "--name-only", "--diff-filter=d", f"{base}...HEAD", "--", "datasets/"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except subprocess.CalledProcessError as err:
        print(f"warning: git diff against {base} failed: {err.stderr.strip()}", file=sys.stderr)
        return []
    return sorted(Path(line).stem for line in out.split() if line.endswith(".toml"))


def sentences(text):
    text = " ".join(text.split())
    return [s for s in re.split(r"(?<=[.!?])\s+", text) if s]


def render(datasets, categories_by_id):
    out = [MARKER, ""]
    n = len(datasets)
    out.append(f"## Dataset preview ({n} changed {'entry' if n == 1 else 'entries'})")
    out.append("")
    out.append("How these entries will read once merged, straight from the generator.")
    out.append("")

    for d in datasets:
        desc = " ".join(d["description"].split())
        sents = sentences(desc)
        out.append(f"### {d['name']}")
        out.append("")
        out.append(f"`/datasets/{d['slug']}/`")
        out.append("")
        for para in re.split(r"\n\s*\n", d["description"].strip()):
            if para.strip():
                out.append("> " + " ".join(para.split()))
                out.append(">")
        if out[-1] == ">":
            out.pop()
        out.append("")

        rows = [
            ("Category", categories_by_id[d["category"]]["name"]),
            ("Format", build.format_labels(d)),
            ("License", d["license"]),
        ]
        if d["author"]:
            rows.append(("Author", d["author"]))
        if d["doi"]:
            rows.append(("DOI", f"[{d['doi']}](https://doi.org/{d['doi']})"))
        rows.append(("Tags", ", ".join(d["tags"]) if d["tags"] else "none"))
        rows.append(("Description", f"{len(sents)} sentences, {len(desc.split())} words"))
        out.append("| Field | Value |")
        out.append("| --- | --- |")
        out.extend(f"| {k} | {v} |" for k, v in rows)
        out.append("")

        out.append("Links, in the order they will render:")
        out.append("")
        for link in d["links"]:
            out.append(f"- **{link['label']}** ({link['type']}) {link['url']}")
        out.append("")

    out.append("<sub>Generated by `ci/preview.py`.</sub>")
    text = "\n".join(out) + "\n"
    if len(text) > COMMENT_LIMIT:
        cut = text[:COMMENT_LIMIT].rsplit("\n", 1)[0]
        text = cut + (
            "\n\n_Preview truncated because it exceeds GitHub's comment size limit. "
            "The full version is in the workflow run summary._\n"
        )
    return text


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", help="git ref to diff against, e.g. origin/main")
    ap.add_argument("--slugs", help="comma-separated slugs, instead of a diff")
    ap.add_argument("--out", required=True, help="file to write the Markdown to")
    args = ap.parse_args(argv)

    if args.slugs:
        wanted = [s.strip() for s in args.slugs.split(",") if s.strip()]
    elif args.base:
        wanted = changed_slugs(args.base)
    else:
        ap.error("pass --base or --slugs")

    out_path = Path(args.out)
    if not wanted:
        out_path.write_text("", encoding="utf-8")
        print("no dataset entries changed")
        return 0

    categories = build.load_categories()
    by_slug = {d["slug"]: d for d in build.load_datasets(categories)}
    missing = [s for s in wanted if s not in by_slug]
    if missing:
        print(f"warning: changed but not loadable: {', '.join(missing)}", file=sys.stderr)
    datasets = [by_slug[s] for s in wanted if s in by_slug]
    if not datasets:
        out_path.write_text("", encoding="utf-8")
        return 0

    categories_by_id = {c["id"]: c for c in categories}
    out_path.write_text(render(datasets, categories_by_id), encoding="utf-8")
    print(f"wrote {out_path} for {len(datasets)} entry/entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
